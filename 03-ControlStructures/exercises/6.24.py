# Rosnąco od 1 do 5 gwiazdek tu zaczynamy od 1 bo napisalismy 1 i 6 to granica wiec bedzie 5 gwiazdek
for i in range(1, 6):
    print("* " * i)

# Malejąco od 4 do 1 gwiazdki, -1 znaczy ze sie zmniejsza , zaczynamy od 4 gwiazdek i idziemy do 0 a 0 to granica wiec konczymy na 1
for i in range(4, 0, -1):
    print("* " * i)